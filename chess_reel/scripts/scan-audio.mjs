// Writes src/audio/available.ts listing the files present in public/audio (run before preview/render).
import fs from 'node:fs';
const dir = new URL('../public/audio/', import.meta.url);
const files = fs.existsSync(dir) ? fs.readdirSync(dir).filter((f) => /\.(wav|mp3|m4a|aac|ogg)$/i.test(f)) : [];
fs.writeFileSync(new URL('../src/audio/available.ts', import.meta.url), `// generated by scripts/scan-audio.mjs\nexport const AVAILABLE: string[] = ${JSON.stringify(files)};\n`);
console.log('audio files:', files);
